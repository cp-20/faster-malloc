#!/usr/bin/env python3
"""Generate size_classes.h: size->class mapping, class sizes, cache limits.

Layout of the size classes:
  * 16-byte granularity up to 512 B   -> 32 classes (idx 0..31)
  * 32-byte granularity up to 1 KiB   -> 16 classes (idx 32..47)
  * 64-byte  up to 2 KiB              -> 16 classes (idx 48..63)
  * 128-byte up to 4 KiB              -> 16 classes (idx 64..79)
  * 256-byte up to 8 KiB              -> 16 classes (idx 80..95)
  * 512-byte up to 16 KiB             -> 16 classes (idx 96..111)
  * 1 KiB   up to 32 KiB              -> 16 classes (idx 112..127)

Sizes <= ARITH_MAX are mapped with pure arithmetic ((size-1)>>4), which keeps
the malloc fast path free of a dependent memory load.  Larger sizes use a
16-byte-granularity lookup table.
"""
import sys

SMALL_MAX = 32768
HEADER = 64
SPAN = 65536
ARITH_MAX = 512

SEGMENTS = [
    (16, 16, 512),
    (32, 544, 1024),
    (64, 1088, 2048),
    (128, 2176, 4096),
    (256, 4352, 8192),
    (512, 8704, 16384),
    (1024, 17408, 32768),
]


def build_classes():
    sizes = []
    for step, first, last in SEGMENTS:
        v = first
        while v <= last:
            sizes.append(v)
            v += step
    return sizes


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "size_classes.h"
    sizes = build_classes()
    nclass = len(sizes)
    assert nclass <= 256, nclass
    assert all(s % 16 == 0 for s in sizes), "class sizes must be 16B multiples"

    # The class of a request is the first class whose block is large enough.
    def cls_of(sz):
        for i, s in enumerate(sizes):
            if s >= sz:
                return i
        raise AssertionError("no class for %d" % sz)

    # Every size must map to a class that can actually hold it.  This is the
    # invariant a mis-indexed table breaks: a block smaller than the request
    # means the caller writes past the end of its allocation.
    for sz in range(1, SMALL_MAX + 1):
        c = cls_of(sz)
        assert sizes[c] >= sz, (sz, c, sizes[c])

    # table for sizes in (ARITH_MAX, SMALL_MAX]
    tbl_base = ARITH_MAX + 1
    tbl_n = ((SMALL_MAX - tbl_base) >> 4) + 1
    table = [0] * tbl_n
    j = 0
    for i in range(tbl_n):
        bucket_max = tbl_base + (i << 4) + 15
        while j < nclass - 1 and sizes[j] < bucket_max:
            j += 1
        table[i] = j
        # the whole bucket must land in the same class
        assert sizes[j] >= bucket_max, (bucket_max, j, sizes[j])

    limits = [max(4, min(256, (64 * 1024) // s)) for s in sizes]
    blocks = [(SPAN - HEADER) // s for s in sizes]

    # The table v1 uses: kClassOf[(size + 15) >> 4].  Bucket i covers the
    # request sizes (16*i-15 .. 16*i], so every size in the bucket must land
    # in the same class and that class must hold the largest of them.
    kof_n = ((SMALL_MAX + 15) >> 4) + 1
    kof = [0] * kof_n
    for i in range(kof_n):
        hi = 16 * i
        c = cls_of(max(hi, 1))
        if hi >= 1:
            lo = max(1, hi - 15)
            assert cls_of(lo) == c, (i, lo, hi, cls_of(lo), c)
        assert sizes[c] >= max(hi, 1), (i, hi, c, sizes[c])
        kof[i] = c

    import os
    refill_batch = int(os.environ.get("FM_REFILL_BATCH", "64"))

    with open(out, "w") as f:
        f.write("/* Generated by gen_classes.py -- do not edit. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define SMALL_MAX {SMALL_MAX}\n")
        f.write(f"#define CLASS_COUNT {nclass}\n")
        f.write(f"#define SPAN_SIZE {SPAN}\n")
        f.write(f"#define HEADER_SIZE {HEADER}\n")
        f.write(f"#define ARITH_MAX {ARITH_MAX}\n")
        f.write(f"#define TABLE_BASE {tbl_base}\n")
        f.write(f"#define TABLE_SIZE {tbl_n}\n")
        f.write("#define SPAN_MASK (~(uintptr_t)(SPAN_SIZE - 1u))\n")
        f.write("#define LARGE_CLASS 0xFFFFFFFFu\n")
        f.write("#define SPAN_MAGIC 0x5A6E4C5Au\n")
        f.write(f"#define REFILL_BATCH {refill_batch}\n\n")
        f.write("static const uint8_t kClassTable[%d] = {\n" % tbl_n)
        for i in range(0, tbl_n, 32):
            f.write("    " + ",".join(str(x) for x in table[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint8_t kClassOf[%d] = {\n" % kof_n)
        for i in range(0, kof_n, 32):
            f.write("    " + ",".join(str(x) for x in kof[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t kClassSize[%d] = {\n" % nclass)
        for i in range(0, nclass, 32):
            f.write("    " + ",".join(str(x) for x in sizes[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t kClassLimit[%d] = {\n" % nclass)
        for i in range(0, nclass, 32):
            f.write("    " + ",".join(str(x) for x in limits[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint32_t kClassBlocks[%d] = {\n" % nclass)
        for i in range(0, nclass, 32):
            f.write("    " + ",".join(str(x) for x in blocks[i:i + 32]) + ",\n")
        f.write("};\n")
    print(f"classes={nclass} table={tbl_n}", file=sys.stderr)


if __name__ == "__main__":
    main()
