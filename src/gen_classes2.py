#!/usr/bin/env python3
"""Generate size_classes2.h -- v2 size classes and dispatch tables.

Class numbering
---------------
The class index is chosen so that the *common* dispatch needs no
correction at all:

    class = (size + 15) >> 4        for size <= 512

Class 0 exists only to serve a request for 0 bytes; class c >= 1 serves the
sizes (16*(c-1), 16*c].  Above 512 the ladder coarsens and a byte lookup
table is used.

The ladder (all sizes are multiples of 16, so every returned pointer is
16-byte aligned as the C standard requires):

    16 .. 128    step 16    ->  8 classes   (idx  1..8)
    144 .. 512   step 16    -> 24 classes   (idx  9..32)
    544 .. 1024  step 32    -> 16 classes   (idx 33..48)
    1088 .. 2048 step 64    -> 16 classes   (idx 49..64)
    2176 .. 4096 step 128   -> 16 classes   (idx 65..80)
    4352 .. 8192 step 256   -> 16 classes   (idx 81..96)
    8704 .. 16384 step 512  -> 16 classes   (idx 97..112)
    17408 .. 32768 step 1024-> 16 classes   (idx 113..128)
    = 129 classes in total (index 0 is the size-0 class)
"""
import os
import sys

SMALL_MAX = 32768
HEADER = 64
SPAN = 65536
ARITH_MAX = 512

SEGMENTS = [
    (16, 16, 128),
    (16, 144, 512),
    (32, 544, 1024),
    (64, 1088, 2048),
    (128, 2176, 4096),
    (256, 4352, 8192),
    (512, 8704, 16384),
    (1024, 17408, 32768),
]


def build():
    """Return the class ladder: index 0 is the size-0 class, index c>=1 has
    block size 16*c for the first 32 classes and then follows the ladder."""
    sizes = [16]  # class 0: a request for 0 bytes
    for step, first, last in SEGMENTS:
        v = first
        while v <= last:
            sizes.append(v)
            v += step
    return sizes


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "size_classes2.h"
    sizes = build()
    n = len(sizes)
    assert n <= 256, n
    assert all(s % 16 == 0 for s in sizes), "class sizes must be 16B multiples"
    assert sizes[-1] == SMALL_MAX, sizes[-1]

    def cls_of(sz):
        """Class that serves a request of `sz` bytes."""
        if sz == 0:
            return 0
        for i, s in enumerate(sizes):
            if i == 0:
                continue
            if s >= sz:
                return i
        raise AssertionError("no class for %d" % sz)

    # The arithmetic range must be exactly 16-byte granular so that
    # class == (size + 15) >> 4 holds for every size in 1..ARITH_MAX.
    n_arith = 0
    for i, s in enumerate(sizes):
        if i >= 1 and s <= ARITH_MAX:
            n_arith = i
    for sz in range(1, ARITH_MAX + 1):
        assert cls_of(sz) == (sz + 15) >> 4, (sz, cls_of(sz))

    # Every class must be able to hold every size that maps to it.  This is
    # the invariant that a mis-indexed table breaks: a block smaller than
    # the request means the caller writes past the end of its allocation.
    for i in range(1, n):
        lo = 1 if i == 1 else prev + 1
        assert sizes[i] >= lo, (i, lo, sizes[i])
        prev = sizes[i]

    # Byte table for the sizes above ARITH_MAX, indexed by (size + 15) >> 4.
    #
    # Bucket i covers the request sizes (16*i-15 .. 16*i), so every size in
    # the bucket must map to the same class, and that class must be able to
    # hold the *largest* size in the bucket.
    big_n = ((SMALL_MAX + 15) >> 4) + 1
    big = [0] * big_n
    for i in range(big_n):
        if i == 0:
            big[0] = 0  # a request for 0 bytes
            continue
        hi = 16 * i
        lo = max(1, hi - 15)
        c_hi = cls_of(hi)
        c_lo = cls_of(lo)
        assert c_hi == c_lo, (i, lo, hi, c_lo, c_hi)
        assert sizes[c_hi] >= hi, (i, hi, sizes[c_hi])
        big[i] = c_hi

    # Local cache limit: the number of blocks a thread may hold in its
    # private free list before handing the list to the shared central list.
    #
    # It trades memory retained per thread against how often the flush
    # branch is taken.  With a small limit the flush fires often and the
    # branch mispredicts every time (measured on the churn workload: 0.9%
    # of all branches mispredict at a limit of 16, 0.2% at 256).
    #
    # The limit is also bounded by the class size so that a thread never
    # holds an unreasonable number of bytes in one class.
    cap = int(os.environ.get("FM_LIMIT_CAP", "256"))
    limits = []
    for s in sizes:
        lim = (64 * 1024) // s
        limits.append(max(4, min(cap, lim)))

    # Inclusive range of request sizes that map to each class.
    lo = [0] * n
    hi = [0] * n
    prev = 0
    for i, s in enumerate(sizes):
        if i == 0:
            lo[0] = 0
            hi[0] = 0
            continue
        lo[i] = prev + 1
        hi[i] = s
        prev = s

    with open(out, "w") as f:
        f.write("/* Generated by gen_classes2.py -- do not edit. */\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define SMALL_MAX {SMALL_MAX}\n")
        f.write(f"#define CLASS_COUNT {n}\n")
        f.write(f"#define ARITH_MAX {ARITH_MAX}\n")
        f.write(f"#define ARITH_CLASSES {n_arith}\n")
        f.write(f"#define BIG_TABLE_SIZE {big_n}\n")
        f.write("#define SPAN_SIZE %du\n" % SPAN)
        f.write("#define HEADER_SIZE %du\n" % HEADER)
        f.write("#define SPAN_MASK (~(uintptr_t)(SPAN_SIZE - 1u))\n")
        f.write("#define LARGE_CLASS 0xFFFFFFFFu\n")
        f.write("#define SPAN_MAGIC 0x5A6E4C5Au\n")
        f.write("#define ALIGNED_MAGIC 0xA110CEDAu\n\n")
        f.write("static const uint8_t kClassBig[%d] = {\n" % big_n)
        for i in range(0, big_n, 32):
            f.write("    " + ",".join(str(x) for x in big[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t kClassSize[%d] = {\n" % n)
        for i in range(0, n, 32):
            f.write("    " + ",".join(str(x) for x in sizes[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t kClassLimit[%d] = {\n" % n)
        for i in range(0, n, 32):
            f.write("    " + ",".join(str(x) for x in limits[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t kClassLo[%d] = {\n" % n)
        for i in range(0, n, 32):
            f.write("    " + ",".join(str(x) for x in lo[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t kClassHi[%d] = {\n" % n)
        for i in range(0, n, 32):
            f.write("    " + ",".join(str(x) for x in hi[i:i + 32]) + ",\n")
        f.write("};\n")
    print(
        "classes=%d arith_classes=%d big_table=%d limit_cap=%d"
        % (n, n_arith, big_n, cap),
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
